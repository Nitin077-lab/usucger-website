#!/usr/bin/env python3
"""Build the conference list on pages/conferences.html from data/conferences.json.

Each event: name, start (YYYY-MM-DD), optional end, location, url, icon, note,
year_only (true when only the year is known). Events that have ended are left
out at build time, and the browser hides any that pass between builds.
Run:  python3 gen_conferences.py && python3 build.py
"""
import json, os, re
from datetime import date

ROOT = os.path.dirname(os.path.abspath(__file__))
events = json.load(open(os.path.join(ROOT, "data", "conferences.json"), encoding="utf-8"))
today = date.today().isoformat()
M = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace("&amp;#", "&#").replace("&amp;nbsp;", "&nbsp;")


def when(e):
    s = date.fromisoformat(e["start"])
    if e.get("year_only"):
        return str(s.year)
    if not e.get("end"):
        return "%d %s %d" % (s.day, M[s.month - 1], s.year)
    t = date.fromisoformat(e["end"])
    if (s.year, s.month) == (t.year, t.month):
        return "%d&ndash;%d %s %d" % (s.day, t.day, M[s.month - 1], s.year)
    return "%d %s &ndash; %d %s %d" % (s.day, M[s.month - 1], t.day, M[t.month - 1], t.year)


up = sorted([e for e in events if (e.get("end") or (e["start"][:4] + "-12-31" if e.get("year_only") else e["start"])) >= today],
            key=lambda e: e["start"])
years = []
for e in up:
    y = e["start"][:4]
    if y not in years:
        years.append(y)
last = up[-1]["start"][:7] if up else today[:7]
out = ['<!-- conferences:start (generated by gen_conferences.py from data/conferences.json) -->',
       '<p class="lead" style="margin-bottom:1.6rem">%d upcoming events through %s, listed by start date. Past events drop off automatically.</p>' % (len(up), up[-1]["start"][:4] if up else "")]
for y in years:
    out.append('<h2 style="color:var(--cobalt-dk);margin-bottom:1.2rem">%s</h2>' % y)
    out.append('<div class="linklist" style="margin-bottom:2.4rem">')
    for e in [x for x in up if x["start"][:4] == y]:
        end = e.get("end") or (e["start"][:4] + "-12-31" if e.get("year_only") else e["start"])
        meta = when(e) + " &middot; " + esc(e["location"])
        if e.get("note"):
            meta += ' &middot; <strong style="color:var(--amber)">%s</strong>' % esc(e["note"])
        out.append('  <a class="linkrow conf-row" data-end="%s" href="%s" target="_blank" rel="noopener"><div class="linkrow-ic">%s</div><div class="linkrow-body"><div class="linkrow-title">%s</div><div class="linkrow-meta">%s</div></div></a>'
                   % (end, e["url"], e.get("icon", "&#128197;"), esc(e["name"]), meta))
    out.append('</div>')
out.append('<script>document.addEventListener("DOMContentLoaded",function(){var t=new Date().toISOString().slice(0,10);document.querySelectorAll(".conf-row[data-end]").forEach(function(r){if(r.dataset.end<t)r.remove()});document.querySelectorAll(".linklist").forEach(function(l){if(!l.children.length){var h=l.previousElementSibling;l.remove();if(h&&h.tagName==="H2")h.remove()}})});</script>')
out.append('<!-- conferences:end -->')
block = "\n".join(out)

p = os.path.join(ROOT, "pages", "conferences.html")
s = open(p, encoding="utf-8").read()
if "<!-- conferences:start" in s:
    s = re.sub(r"<!-- conferences:start.*?<!-- conferences:end -->", lambda m: block, s, flags=re.S)
else:
    a = s.index('<h2 style="color:var(--cobalt-dk);margin-bottom:1.2rem">2026 and beyond</h2>')
    b = s.index("</div>\n      </div>\n\n      <aside")
    s = s[:a] + block + "\n" + s[b:]
open(p, "w", encoding="utf-8").write(s)
print("conferences: %d upcoming of %d" % (len(up), len(events)))
